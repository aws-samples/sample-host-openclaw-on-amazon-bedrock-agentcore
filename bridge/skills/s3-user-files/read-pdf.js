/**
 * read_pdf_text — Extract the text of a PDF in a user's S3-namespaced storage.
 * Usage: node read-pdf.js <user_id> <filename> [--pages 1-20] [--max-chars 40000]
 *        node read-pdf.js --self-test
 *
 * Prints a header (page count, the pages shown, where to continue), then the
 * text between random BEGIN/END markers. Defaults: pages 1-20 and 40,000
 * characters; at most 50 pages and 120,000 characters per call. Refuses
 * objects larger than 25 MB and never writes the file to disk.
 *
 * clawpdf (PDFium compiled to WebAssembly) parses the PDF in a child node
 * process that is killed after 30 seconds, so a damaged or hostile file cannot
 * hang the tool call. --self-test parses an embedded PDF the same way, without
 * S3 or AWS settings.
 */
