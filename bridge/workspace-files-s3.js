/**
 * S3 location of the per-user workspace Markdown files (AGENTS.md, SOUL.md,
 * USER.md, IDENTITY.md, TOOLS.md, MEMORY.md) that the Bedrock proxy splices
 * into the Converse `system` block.
 *
 * The files live at `_system/<namespace>/<filename>` at the bucket root, which
 * is outside the user's own `<namespace>/` prefix. The scoped STS session
 * policy (bridge/scoped-credentials.js) only allows object access under
 * `<namespace>/*` and only lists `<namespace>/*`, so neither the in-microVM
 * agent nor the user-files skill or gateway tool can read, write or list these
 * keys. Only the proxy and the contract server, which use the execution role,
 * write them. No extra Deny statement is needed, so the session policy stays
 * the same size.
 *
 * Earlier releases kept these files at `<namespace>/<filename>`. The first
 * read for a file whose new key is empty copies the legacy object across with
 * a conditional write (If-None-Match: *), so an existing file in the new
 * location is never overwritten. The legacy object is never deleted.
 */
"use strict";

const SYSTEM_ROOT_PREFIX = "_system/";

function assertSafePart(value, what) {
  if (typeof value !== "string" || !value || value.includes("/") || value.includes("..")) {
    throw new Error(`invalid ${what}`);
  }
}

/** Key the proxy reads and writes for a workspace file. */
function workspaceKey(namespace, filename) {
  assertSafePart(namespace, "namespace");
  assertSafePart(filename, "filename");
  return `${SYSTEM_ROOT_PREFIX}${namespace}/${filename}`;
}

/** Key used by earlier releases, inside the user-writable namespace prefix. */
function legacyWorkspaceKey(namespace, filename) {
  assertSafePart(namespace, "namespace");
  assertSafePart(filename, "filename");
  return `${namespace}/${filename}`;
}

function isNotFound(err) {
  return !!err && (err.name === "NoSuchKey" || err.name === "NotFound" ||
    err.$metadata?.httpStatusCode === 404);
}

function isPreconditionFailed(err) {
  return !!err && (err.name === "PreconditionFailed" ||
    err.$metadata?.httpStatusCode === 412 || err.$metadata?.httpStatusCode === 409);
}

async function bodyToString(body) {
  if (body == null) return "";
  if (typeof body === "string") return body;
  if (typeof body.transformToString === "function") return body.transformToString("utf-8");
  const chunks = [];
  for await (const chunk of body) chunks.push(Buffer.from(chunk));
  return Buffer.concat(chunks).toString("utf-8");
}

// AGENTS.md is generated by the contract server on every container start and
// uploaded to the new key, so a legacy copy is never carried across.
const NO_LEGACY_COPY = new Set(["AGENTS.md"]);

/**
 * Read a workspace file. Returns { content, source } where source is
 * "system", "migrated" or "none". Throws on unexpected S3 errors so the
 * caller decides how to log them.
 *
 * @param {object} opts
 * @param {{send: Function}} opts.s3 - S3 client (execution role)
 * @param {object} opts.commands - { GetObjectCommand, PutObjectCommand }
 * @param {string} opts.bucket
 * @param {string} opts.namespace
 * @param {string} opts.filename
 * @param {Function} [opts.log]
 */
async function readWorkspaceFile({ s3, commands, bucket, namespace, filename, log = () => {} }) {
  const { GetObjectCommand, PutObjectCommand } = commands;
  const key = workspaceKey(namespace, filename);
  try {
    const resp = await s3.send(new GetObjectCommand({ Bucket: bucket, Key: key }));
    return { content: (await bodyToString(resp.Body)).trim(), source: "system" };
  } catch (err) {
    if (!isNotFound(err)) throw err;
  }
  if (NO_LEGACY_COPY.has(filename)) return { content: "", source: "none" };

  // One-time copy from the legacy location.
  let legacy;
  try {
    const resp = await s3.send(new GetObjectCommand({
      Bucket: bucket, Key: legacyWorkspaceKey(namespace, filename),
    }));
    legacy = (await bodyToString(resp.Body)).trim();
  } catch (err) {
    if (isNotFound(err)) return { content: "", source: "none" };
    throw err;
  }
  if (!legacy) return { content: "", source: "none" };

  try {
    await s3.send(new PutObjectCommand({
      Bucket: bucket,
      Key: key,
      Body: legacy,
      ContentType: "text/markdown; charset=utf-8",
      IfNoneMatch: "*",
    }));
    log(`[proxy] Copied legacy ${filename} for ${namespace} to ${SYSTEM_ROOT_PREFIX}`);
    return { content: legacy, source: "migrated" };
  } catch (err) {
    if (!isPreconditionFailed(err)) throw err;
    // Another request wrote the new key first; that object wins.
    const resp = await s3.send(new GetObjectCommand({ Bucket: bucket, Key: key }));
    return { content: (await bodyToString(resp.Body)).trim(), source: "system" };
  }
}

/**
 * Write a workspace file only when the key does not exist yet (seeding).
 * Returns true when written, false when the key already existed.
 */
async function seedWorkspaceFile({ s3, commands, bucket, namespace, filename, content }) {
  const { PutObjectCommand } = commands;
  try {
    await s3.send(new PutObjectCommand({
      Bucket: bucket,
      Key: workspaceKey(namespace, filename),
      Body: content,
      ContentType: "text/markdown; charset=utf-8",
      IfNoneMatch: "*",
    }));
    return true;
  } catch (err) {
    if (isPreconditionFailed(err)) return false;
    throw err;
  }
}

/**
 * Upload the contract-generated AGENTS.md to the key the proxy reads.
 * Always overwrites: the contract regenerates it on every container start.
 * Callers must pass an execution-role client, not the scoped-credential
 * client, because the scoped session policy has no access to _system/.
 */
async function publishAgentsMd({ s3, commands, bucket, namespace, content, abortSignal }) {
  const { PutObjectCommand } = commands;
  const key = workspaceKey(namespace, "AGENTS.md");
  await s3.send(new PutObjectCommand({
    Bucket: bucket,
    Key: key,
    Body: content,
    ContentType: "text/markdown",
  }), abortSignal ? { abortSignal } : undefined);
  return key;
}

module.exports = {
  SYSTEM_ROOT_PREFIX,
  publishAgentsMd,
  NO_LEGACY_COPY,
  workspaceKey,
  legacyWorkspaceKey,
  readWorkspaceFile,
  seedWorkspaceFile,
};
